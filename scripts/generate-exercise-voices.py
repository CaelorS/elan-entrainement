"""Generate French exercise announcements from a name-only database inventory.
Usage: python3 scripts/generate-exercise-voices.py inventory.json
Requires the macOS Thomas voice and ffmpeg. Names are data, never shell code.
"""
import concurrent.futures, hashlib, json, pathlib, subprocess, sys, tempfile, unicodedata
root=pathlib.Path(__file__).resolve().parent.parent
inventory=json.loads(pathlib.Path(sys.argv[1]).read_text())
normal=lambda s:' '.join(unicodedata.normalize('NFC',s).strip().lower().split())
names={normal(e['nom']):e['nom'].strip() for e in inventory}
catalogue={key:'names/'+hashlib.sha256(key.encode()).hexdigest()[:16] for key in names}
system={'repos':'Repos.','cote_gauche':'Côté gauche.','cote_droite':'Côté droit.','fini':'Séance terminée.','on_commence':'On commence.'}
tasks=[(catalogue[key],label) for key,label in names.items()]+list(system.items())
(root/'public/audio/names').mkdir(exist_ok=True)
def generate(task):
 key,text=task;output=root/'public/audio'/f'{key}.m4a'
 with tempfile.TemporaryDirectory(prefix='elan-voice-') as tmp:
  txt=pathlib.Path(tmp)/'text.txt';txt.write_text(text)
  wav=pathlib.Path(tmp)/'speech.aiff'
  subprocess.run(['say','-v','Thomas','-r','175','-f',str(txt),'-o',str(wav)],check=True)
  subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-i',str(wav),'-af','silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-16:TP=-1.5:LRA=11','-ac','1','-ar','24000','-c:a','aac','-b:a','64k',str(output)],check=True)
  info=json.loads(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration,size','-of','json',str(output)]))['format']
  if float(info.get('duration',0))<.2 or int(info['size'])<1000: raise ValueError(f'Empty audio: {key}')
  return {'key':key,'text':text,'duration':float(info['duration']),'bytes':int(info['size'])}
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
 results=[]
 for item in pool.map(generate,tasks):
  results.append(item)
  if len(results)%20==0: print(f'{len(results)}/{len(tasks)} files verified',flush=True)
(root/'lib/exercise-voice-catalogue.ts').write_text('// Generated by scripts/generate-exercise-voices.py; exact names avoid cross-account ID collisions.\nexport const exerciseVoiceCatalogue:Record<string,string>='+json.dumps(catalogue,ensure_ascii=False,indent=2)+';\n')
manifest=json.loads((root/'public/audio/manifest.json').read_text())
(root/'public/audio/manifest.json').write_text(json.dumps(sorted(set(manifest)|set(catalogue.values())),ensure_ascii=False,indent=2)+'\n')
(root.parent/'outputs/exercise-audio-audit-2026-11-06.json').write_text(json.dumps(results,ensure_ascii=False,indent=2))
print(f'Completed: {len(names)} exercise names, {len(system)} prompts, {sum(r["bytes"] for r in results)} bytes',flush=True)
